CREATE TABLE yawrd.yaw001_contribution_events (
  network text NOT NULL CHECK (network = 'testnet'),
  project_id text NOT NULL CHECK (project_id = 'yaw-001'),
  task_ref text NOT NULL CHECK (task_ref IN ('task-a', 'task-b')),
  event_kind text NOT NULL CHECK (event_kind IN ('request', 'acknowledgement')),
  pr_url text NOT NULL,
  pr_head_sha text NOT NULL,
  merge_commit_sha text NOT NULL,
  actor_account_id text NOT NULL CHECK (
    length(actor_account_id) BETWEEN 2 AND 64
    AND actor_account_id ~ '^[a-z0-9]+([._-][a-z0-9]+)*$'
  ),
  application_id uuid,
  description text,
  recipient_account_id text,
  consent_version text NOT NULL,
  -- NULL/NULL means exact historical date/time unknown, NOT newly accepted.
  -- A reported calendar date and an exact instant are alternatives, never rounded.
  historical_accepted_on date,
  historical_accepted_at timestamptz,
  historical_acceptance_evidence text,
  recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  -- Acknowledgements must reference an existing request for this exact task.
  -- Generated by the database: callers cannot redirect the dependency or omit it.
  request_event_kind text GENERATED ALWAYS AS (
    CASE WHEN event_kind = 'acknowledgement' THEN 'request'::text ELSE NULL::text END
  ) STORED,
  PRIMARY KEY (network, project_id, task_ref, event_kind),
  UNIQUE (network, project_id, pr_url, event_kind),
  FOREIGN KEY (network, project_id) REFERENCES yawrd.projects(network, id),
  -- MATCH SIMPLE deliberately permits NULL application_id for founder-only ack.
  FOREIGN KEY (application_id, network, project_id)
    REFERENCES yawrd.applications(id, network, project_id),
  CONSTRAINT yaw001_acknowledgement_request_fk
    FOREIGN KEY (network, project_id, task_ref, request_event_kind)
    REFERENCES yawrd.yaw001_contribution_events(network, project_id, task_ref, event_kind),
  CONSTRAINT yaw001_canonical_pr CHECK (
    (task_ref = 'task-a'
      AND pr_url = 'https://github.com/vandigital/yawrd-build-progress/pull/2'
      AND pr_head_sha = 'a97c28df2c86b80a7ff161ab82cc13fc6fcdd6c8'
      AND merge_commit_sha = 'aede263a82da7514f9eac9e4436ba3113a1eebd3')
    OR (task_ref = 'task-b'
      AND pr_url = 'https://github.com/vandigital/yawrd-build-progress/pull/4'
      AND pr_head_sha = 'c0c4277839e9c5d8b563970306a9dbde782babe1'
      AND merge_commit_sha = '26d2d5e8b087749f47696ee27732a42f32929da7')
  ),
  CONSTRAINT yaw001_event_payload CHECK (
    (event_kind = 'request'
      AND application_id IS NOT NULL
      AND description IS NOT NULL
      AND length(description) BETWEEN 1 AND 1000
      AND description = btrim(description)
      AND description !~ '[[:cntrl:]]'
      AND recipient_account_id IS NOT NULL
      AND recipient_account_id = actor_account_id
      AND consent_version = 'yaw001-contribution-request-v1'
      AND historical_accepted_on IS NULL
      AND historical_accepted_at IS NULL
      AND historical_acceptance_evidence IS NULL)
    OR (event_kind = 'acknowledgement'
      AND application_id IS NULL
      AND description IS NULL
      AND recipient_account_id IS NULL
      AND consent_version = 'yaw001-prior-acceptance-ack-v1'
      AND historical_acceptance_evidence IS NOT NULL
      AND length(historical_acceptance_evidence) BETWEEN 1 AND 2000
      AND historical_acceptance_evidence = btrim(historical_acceptance_evidence)
      AND historical_acceptance_evidence !~ '[[:cntrl:]]'
      AND (historical_accepted_on IS NULL OR historical_accepted_at IS NULL))
  ),
  CONSTRAINT yaw001_historical_time CHECK (
    (historical_accepted_at IS NULL OR
      (isfinite(historical_accepted_at) AND historical_accepted_at <= recorded_at))
    AND (historical_accepted_on IS NULL OR
      (isfinite(historical_accepted_on) AND
       historical_accepted_on <= (recorded_at AT TIME ZONE 'Asia/Manila')::date))
  )
);

-- Consistency guards, NOT end-user session authentication. The server must also
-- derive actor from a live session inside INSERT ... SELECT; never trust JSON.
CREATE FUNCTION yawrd.check_yaw001_contribution_event() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path = pg_catalog, yawrd AS $$
DECLARE
  expected_owner text;
BEGIN
  -- Neither caller-supplied receipt time nor retries may backdate a new fact.
  NEW.recorded_at := clock_timestamp();
  IF NOT EXISTS (
    SELECT 1 FROM yawrd.projects p
    WHERE p.network = NEW.network AND p.id = NEW.project_id
      AND p.network = 'testnet' AND p.id = 'yaw-001'
      AND p.dao_account_id = 'demo.factory.yawrd.testnet'
      AND p.creator_account_id = 'yawrd1.testnet' AND p.published_at IS NOT NULL
  ) THEN
    RAISE EXCEPTION 'yaw001_published_identity_required' USING ERRCODE = '23514';
  END IF;

  IF NEW.event_kind = 'request' THEN
    -- Task B binding is founder-approved, corroborated by preserved public PR #4.
    -- Task A stays NULL. No authority is delegated from keelbase.testnet.
    -- Any replacement requires explicit review of this inactive draft (or a
    -- separately authorized migration after activation). No runtime edit grant.
    SELECT ownership.owner_account_id INTO expected_owner
    FROM (VALUES ('task-a', NULL::text), ('task-b', 'keelbase1.testnet'::text))
      AS ownership(task_ref, owner_account_id)
    WHERE ownership.task_ref = NEW.task_ref;
    IF expected_owner IS NULL THEN
      RAISE EXCEPTION 'task_owner_unconfirmed' USING ERRCODE = '23514';
    END IF;
    IF expected_owner IS DISTINCT FROM NEW.actor_account_id THEN
      RAISE EXCEPTION 'task_owner_required' USING ERRCODE = '23514';
    END IF;
    IF NOT EXISTS (
      SELECT 1 FROM yawrd.applications a JOIN yawrd.review_decisions d
        ON d.application_id = a.id AND d.network = a.network
        AND d.project_id = a.project_id AND d.decision = 'approved'
      WHERE a.id = NEW.application_id AND a.network = NEW.network
        AND a.project_id = NEW.project_id AND a.account_id = NEW.actor_account_id
    ) THEN
      RAISE EXCEPTION 'approved_task_owner_required' USING ERRCODE = '23514';
    END IF;
  ELSIF NEW.event_kind = 'acknowledgement' THEN
    IF NOT EXISTS (
      SELECT 1 FROM yawrd.projects p
      WHERE p.network = NEW.network AND p.id = NEW.project_id
        AND p.creator_account_id = NEW.actor_account_id
    ) THEN
      RAISE EXCEPTION 'creator_only' USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

